"""
Собственные исключения для предметной области сервисов.

Зачем нужны свои исключения?
- Встроенные исключения Python (ValueError, KeyError) не несут смысла предметной области.
- Свои исключения позволяют ловить строго определённые ошибки бизнес-логики.
- Например: ItemNotFoundError — сервис не найден, DuplicateItemError — дубликат.
- В cli.py мы ловим эти исключения и выводим понятное сообщение пользователю.
"""


class ItemNotFoundError(Exception):
    """
    Выбрасывается, когда сервис с указанным именем не найден в коллекции.
    Например: пользователь пытается удалить/найти несуществующий сервис.
    """
    def __init__(self, name: str) -> None:
        self.service_name: str = name  # сохраняем имя, которое искали
        super().__init__(f"Сервис '{name}' не найден в коллекции")


class DuplicateItemError(Exception):
    """
    Выбрасывается при попытке добавить сервис с именем, которое уже есть в коллекции.
    Это защита от дубликатов — в предметной области имена сервисов уникальны.
    """
    def __init__(self, name: str) -> None:
        self.service_name: str = name
        super().__init__(f"Сервис с именем '{name}' уже существует")


class InvalidInputError(Exception):
    """
    Выбрасывается при некорректном вводе пользователя.
    Например: ввели буквы вместо числа, выбрали несуществующий пункт меню.
    """
    def __init__(self, message: str = "Некорректный ввод") -> None:
        super().__init__(message)