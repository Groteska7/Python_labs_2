"""
Точка входа в приложение.
Запускает бизнес-логику (App) и CLI-интерфейс (cli.run).
"""

from src.lab07.app import App  # бизнес-логика: загрузка данных, CRUD, сохранение
from src.lab07.cli import run  # CLI: меню, ввод/вывод, форматирование


def main() -> None:
    """
    Главная функция.
    1. Создаёт объект App — он сам загружает данные из JSON при инициализации.
    2. Запускает цикл меню через cli.run().
    3. При выходе из меню App.save_data() сохранит данные обратно в JSON.
    """
    app: App = App()  # создаём приложение (автозагрузка данных)
    run(app)          # запускаем интерактивное меню


if __name__ == "__main__":
    main()